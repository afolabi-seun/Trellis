using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Trellis.Api.Modules.RentLedger.Domain.Entities;

namespace Trellis.Api.Modules.RentLedger.Infrastructure.Data.Configurations;

/// <summary>One change per schedule per date — a unique index, which makes a retried renewal acceptance idempotent. renewal_offer_id is a plain column, like every other cross-module id.</summary>
public sealed class RentChangeConfiguration : IEntityTypeConfiguration<RentChange>
{
    public void Configure(EntityTypeBuilder<RentChange> builder)
    {
        builder.ToTable("rent_change", schema: "trellis_rentledger");
        builder.HasKey(c => c.RentChangeId);

        // Never generated by the database: a new change is added explicitly (RentScheduleRepository.AddRentChangeAsync), not inferred from a key EF can't tell apart from an existing row's.
        builder.Property(c => c.RentChangeId).HasColumnName("rent_change_id").ValueGeneratedNever();
        builder.Property(c => c.TenantId).HasColumnName("tenant_id");
        builder.Property(c => c.RentScheduleId).HasColumnName("rent_schedule_id");
        builder.Property(c => c.EffectiveFrom).HasColumnName("effective_from");
        builder.Property(c => c.RentAmount).HasColumnName("rent_amount").HasColumnType("numeric(12,2)");
        builder.Property(c => c.RenewalOfferId).HasColumnName("renewal_offer_id");
        builder.Property(c => c.CreatedBy).HasColumnName("created_by");
        builder.Property(c => c.CreatedAt).HasColumnName("created_at");

        builder.HasIndex(c => c.TenantId);
        builder.HasIndex(c => new { c.RentScheduleId, c.EffectiveFrom }).IsUnique();
    }
}
